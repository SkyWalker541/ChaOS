#!/usr/bin/env python3
"""ChaOS's boot animation for the website: web/boot.js.

Run from the repo root:  python3 tools/genwebboot.py

The same squares and paths as the Brick's boot (tools/genchaosmotion.py's
cells(), from the same seed), written as data for web/app.js to fly in on a
canvas, so the site opens the way the device does.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import genchaosmotion as m   # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    cs = m.cells()
    cols = sorted({c[2] for c in cs})
    data = {
        "w": m.W, "h": m.H, "cell": m.CELL,
        "ground": "#%02x%02x%02x" % m.GROUND,
        "delayMax": m.BOOT_DELAY_MAX, "flight": m.BOOT_FLIGHT,
        "colors": ["#%02x%02x%02x" % c for c in cols],
        # x, y, colour index, dx, dy, distance, delay
        "cells": [[x, y, cols.index(col), round(dx, 4), round(dy, 4), round(d, 1), round(dl, 4)]
                  for x, y, col, dx, dy, d, dl in cs],
    }
    out = os.path.join(ROOT, "web", "boot.js")
    with open(out, "w") as f:
        f.write("/* Generated by tools/genwebboot.py from tools/genchaosmotion.py. */\n")
        f.write("window.CHAOS_BOOT=" + json.dumps(data, separators=(",", ":")) + ";\n")
    print("wrote", out, len(cs), "squares")


if __name__ == "__main__":
    main()
